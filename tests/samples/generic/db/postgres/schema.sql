-- Billing sample; not a real schema.
CREATE TABLE IF NOT EXISTS accounts (
  id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name    TEXT NOT NULL,
  balance NUMERIC(12, 2) DEFAULT 0,
  CHECK (balance >= 0)
);

/* projects belong to one account */
CREATE TABLE IF NOT EXISTS projects (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title      TEXT NOT NULL,
  note       TEXT DEFAULT 'a, b (c)',
  account_id INT NOT NULL REFERENCES accounts (id),
  UNIQUE (account_id, title)
);
CREATE INDEX IF NOT EXISTS idx_projects_title ON projects (title);
CREATE UNIQUE INDEX IF NOT EXISTS unique_account_project_title
  ON projects (account_id,   LOWER(title));
CREATE INDEX idx_projects_note ON projects USING gin (note);
